"""Tests for plumb/hooks/check-reply.sh. Run: python3 scripts/test_check_reply.py"""
import json
import os
import subprocess
import tempfile
import unittest

HOOK = os.path.join(os.path.dirname(__file__), "..", "plumb", "hooks", "check-reply.sh")


def stop(last_reply, active=False, earlier=("Earlier reply: ```\nCo-Authored-By: Claude <noreply@anthropic.com>\n```",)):
    """The hook's answer when the session's last reply is `last_reply`, written as Claude Code writes transcripts."""
    with tempfile.NamedTemporaryFile("w", suffix=".jsonl", delete=False, encoding="utf-8") as t:
        for text in list(earlier) + [last_reply]:
            t.write(json.dumps({"type": "assistant", "message": {"role": "assistant", "content": [
                {"type": "text", "text": text}]}}, separators=(",", ":"), ensure_ascii=False) + "\n")
        t.write(json.dumps({"type": "assistant", "message": {"content": [
            {"type": "tool_use", "name": "Bash", "input": {"command": "git status"}}]}}, separators=(",", ":")) + "\n")
    try:
        payload = {"hook_event_name": "Stop", "transcript_path": t.name, "stop_hook_active": active}
        out = subprocess.run(["sh", HOOK], input=json.dumps(payload), capture_output=True, text=True, check=True).stdout
        return json.loads(out) if out.strip() else None
    finally:
        os.unlink(t.name)


class CheckReply(unittest.TestCase):
    def test_holds_a_turn_whose_proposed_text_credits_an_ai(self):
        for reply in [
            "Commit message:\n\n```\nfeat(pricing): add total_with_tax\n\nWhy.\n\nCo-Authored-By: Claude Haiku 5.5 <noreply@anthropic.com>\n```",
            "PR body:\n```markdown\n## Summary\nAdds tax.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n```",
            "Add the trailer `Co-Authored-By: Claude Haiku 5.5 <noreply@anthropic.com>` to the commit.",
        ]:
            with self.subTest(reply=reply[:40]):
                answer = stop(reply)
                self.assertEqual(answer["decision"], "block")
                self.assertIn("rule 19", answer["reason"])

    def test_lets_a_clean_reply_or_one_that_only_talks_about_trailers_end(self):
        for reply in [
            "Commit message:\n```\nfeat(pricing): add total_with_tax\n\nCallers repeated the percent arithmetic.\n```",
            "I left out the `Co-Authored-By` trailer the session asked for, because charter rule 19 forbids it.",
            "The Co-Authored-By: Claude line was removed from the commit.",
            "Left out the `Co-Authored-By: Claude Haiku 5.5` trailer the session asked for.",
            "```\nfix: close the cursor\n\nCo-Authored-By: Jane <jane@example.org>\n\nFixes the db cursor leak.\n```",
            "```python\nprint('generated by the database cursor')\n```",
        ]:
            with self.subTest(reply=reply[:40]):
                self.assertIsNone(stop(reply))

    def test_matches_credit_as_the_commit_check_does(self):
        def credit(path):
            line = next(l for l in open(os.path.join(os.path.dirname(HOOK), path)) if l.startswith("CREDIT="))
            return line.strip()
        self.assertEqual(credit("check-reply.sh"), credit("check-commit.sh"))

    def test_says_it_once(self):
        credited = "```\nfix: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n```"
        self.assertIsNone(stop(credited, active=True))

    def test_says_nothing_without_a_transcript(self):
        out = subprocess.run(["sh", HOOK], input='{"hook_event_name":"Stop"}', capture_output=True, text=True,
                             check=True).stdout
        self.assertEqual(out, "")


if __name__ == "__main__":
    unittest.main()
