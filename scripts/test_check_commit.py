"""Tests for plumb/hooks/check-commit.sh. Run: python3 scripts/test_check_commit.py"""

import json
import os
import subprocess
import tempfile
import unittest

HOOK = os.path.join(os.path.dirname(__file__), "..", "plumb", "hooks", "check-commit.sh")
GIT = ["git", "-c", "user.email=dev@example.com", "-c", "user.name=Dev", "-c", "commit.gpgsign=false"]


def git(repo, *args):
    subprocess.run(GIT + ["-C", repo, *args], check=True, capture_output=True)


def hook_output(repo, command, output=None, copilot=False):
    # By default the command printed git's success line for the newest commit, as a real commit does.
    if output is None:
        line = subprocess.run(["git", "-C", repo, "log", "-1", "--format=[main %h] %s"], check=True,
                              capture_output=True, text=True).stdout.strip()
        output = line if "commit" in command else ""
    payload = {"hook_event_name": "PostToolUse", "cwd": repo, "tool_name": "Bash",
               "tool_input": {"command": command}, "tool_response": {"stdout": output}}
    env = {k: v for k, v in os.environ.items() if k != "COPILOT_PLUGIN_ROOT"}
    if copilot:
        env["COPILOT_PLUGIN_ROOT"] = "/plugin"
    return subprocess.run(["sh", HOOK], input=json.dumps(payload), capture_output=True,
                          text=True, check=True, env=env).stdout


def run_hook(repo, command, output=None):
    return "isn't Conventional Commits" in hook_output(repo, command, output)


class CheckCommit(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.repo = self.tmp.name
        git(self.repo, "init", "-q")
        git(self.repo, "commit", "-q", "--allow-empty", "-m", "chore: start")

    def tearDown(self):
        self.tmp.cleanup()

    def test_flags_only_a_fresh_non_conventional_commit(self):
        cases = [
            # (subject, command run, flagged)
            ("Add total with tax", "git commit -m 'Add total with tax'", True),
            ("feat: add total with tax", "git commit -m 'feat: add total with tax'", False),
            ("feat(pricing)!: drop float prices", "git commit -m x", False),
            ("Update stuff", "git status", False),
            ("Update stuff", 'git -C "$repo" commit -m "$(cat <<EOF\nUpdate stuff\nEOF\n)"', True),
            ("Update stuff", "npm run commitlint", False),
        ]
        for subject, command, flagged in cases:
            with self.subTest(subject=subject, command=command):
                git(self.repo, "commit", "-q", "--allow-empty", "-m", subject)
                self.assertEqual(run_hook(self.repo, command), flagged)

    def test_flags_a_trailer_crediting_an_ai_tool(self):
        cases = [
            ("feat: add tax\n\nCo-Authored-By: Claude <noreply@anthropic.com>", True),
            ("feat: add tax\n\nGenerated with Claude Code", True),
            ("feat: add tax\n\nWhy: carts need tax.\n\nCo-Authored-By: Sam <sam@example.com>", False),
            ("feat: add tax\n\n\U0001F916 Generated with [Claude Code](https://claude.com/claude-code)", True),
            # Prose that mentions a tool or AI without crediting one.
            ("feat: page orders\n\nPage tokens are generated by the database cursor, so pages are stable.", False),
            ("feat: add ids\n\nIDs generated by the DB; see the AI team's note.", False),
        ]
        for message, flagged in cases:
            with self.subTest(message=message):
                git(self.repo, "commit", "-q", "--allow-empty", "-m", message)
                self.assertEqual("credits an AI tool" in hook_output(self.repo, "git commit -F msg"), flagged)

    def test_flags_first_person_wording(self):
        cases = [
            ("feat: add tax\n\nI added tax because carts need it.", True),
            ("feat: add tax\n\nCarts need tax, so we add it at checkout.", True),
            ("fix: retry once\n\nThis fixes our flaky upload.", True),
            ("feat: add tax\n\nCarts need tax at checkout. Verified by the unit tests.", False),
            ("perf: batch I/O\n\nReads my_var once and keeps buckets in us-east-1.", False),
        ]
        for message, flagged in cases:
            with self.subTest(message=message):
                git(self.repo, "commit", "-q", "--allow-empty", "-m", message)
                self.assertEqual("first person" in hook_output(self.repo, "git commit -F msg"), flagged)

    def test_flags_a_commit_without_a_body(self):
        cases = [("feat: add tax", True), ("feat: add tax\n\nCarts need tax at checkout.", False)]
        for message, flagged in cases:
            with self.subTest(message=message):
                git(self.repo, "commit", "-q", "--allow-empty", "-m", message)
                self.assertEqual("no body" in hook_output(self.repo, "git commit -F msg"), flagged)

    def test_ignores_a_commit_only_mentioned_in_the_output(self):
        git(self.repo, "commit", "-q", "--allow-empty", "-m", "Made by the user")
        self.assertFalse(run_hook(self.repo, "git status", "no changes added to commit"))

    def test_ignores_an_old_commit_when_this_command_made_none(self):
        old = {**os.environ, "GIT_COMMITTER_DATE": "2000-01-01T00:00:00"}
        subprocess.run(GIT + ["-C", self.repo, "commit", "-q", "--allow-empty", "-m", "Old"],
                       check=True, env=old)
        self.assertFalse(run_hook(self.repo, "git commit -m 'nothing to commit'"))

    def test_ignores_a_merge_commit(self):
        git(self.repo, "checkout", "-q", "-b", "side")
        git(self.repo, "commit", "-q", "--allow-empty", "-m", "feat: side")
        git(self.repo, "checkout", "-q", "-")
        git(self.repo, "merge", "-q", "--no-ff", "--no-commit", "side")
        git(self.repo, "commit", "-q", "--no-edit")
        self.assertFalse(run_hook(self.repo, "git commit --no-edit"))

    def test_finds_a_commit_made_in_another_folder(self):
        # The session's folder is the parent; the commit is made in a repository below it.
        with tempfile.TemporaryDirectory() as parent:
            repo = os.path.join(parent, "svc")
            os.makedirs(repo)
            git(repo, "init", "-q")
            git(repo, "commit", "-q", "--allow-empty", "-m", "Add stuff")
            made = subprocess.run(["git", "-C", repo, "log", "-1", "--format=[main %h] %s"], check=True,
                                  capture_output=True, text=True).stdout.strip()
            for command in ["cd svc && git commit -m 'Add stuff'", 'git -C svc commit -m "Add stuff"']:
                with self.subTest(command=command):
                    self.assertTrue(run_hook(parent, command, made))

    def test_flags_skipped_hooks(self):
        git(self.repo, "commit", "-q", "--allow-empty", "-m", "feat: add tax\n\nCarts need tax.")
        self.assertIn("--no-verify", hook_output(self.repo, "git commit --no-verify -m x"))
        self.assertEqual(hook_output(self.repo, "git commit -m x && head -n 5 log"), "")

    def test_flags_pull_request_text_crediting_ai_or_in_the_first_person(self):
        cases = [
            ('gh pr create --title "feat: add tax" --body "Adds tax.\n\nGenerated with Claude Code"', "credits an AI tool"),
            ('gh pr comment 4 --body "I fixed the rounding."', "first person"),
            ('gh issue create --title "Rounding is off" --body "Steps: add 2.345"', None),
        ]
        for command, flag in cases:
            with self.subTest(command=command):
                out = hook_output(self.repo, command)
                if flag:
                    self.assertIn(flag, out)
                else:
                    self.assertEqual(out, "")

    def test_ignores_an_operator_commit_when_this_command_failed(self):
        # The operator committed a moment ago; the agent's own commit then failed or made another commit.
        git(self.repo, "commit", "-q", "--allow-empty", "-m", "Add stuff")
        head = subprocess.run(["git", "-C", self.repo, "rev-parse", "--short", "HEAD"], check=True,
                              capture_output=True, text=True).stdout.strip()
        cases = [
            ("nothing to commit, working tree clean", False),
            ("error: pathspec 'x' did not match any file(s) known to git", False),
            ("[main 0000000] feat: something else", False),
            (f"[main {head}] Add stuff\n 1 file changed", True),
            # A command that made no commit and printed something else, or nothing.
            ("notes.txt:3: git commit -m", False),
            ("", False),
            ("black....Failed", False),
        ]
        for output, flagged in cases:
            with self.subTest(output=output):
                self.assertEqual(run_hook(self.repo, "git commit -m 'feat: x'", output), flagged)
        # A quiet commit prints no success line, so only a failure rules it out.
        self.assertTrue(run_hook(self.repo, "git commit -q -m 'Add stuff'", ""))
        self.assertFalse(run_hook(self.repo, "git commit -q -m 'Add stuff'", "black....Failed"))

    def test_flags_every_way_of_skipping_hooks(self):
        git(self.repo, "commit", "-q", "--allow-empty", "-m", "feat: add tax\n\nCarts need tax.")
        cases = [
            ("git commit -n -m x", True),
            ("git commit -nm x", True),
            ("git commit -anm x", True),
            ("git -c core.hooksPath=/dev/null commit -m x", True),
            ("git commit -m 'bump -minor flag'", False),
            ("git commit -am x", False),
            ('git commit --no-verify -m "fix the commit hook"', True),
            ('git commit -m "$(cat <<EOF\nfeat: x\n\nthe commit step\nEOF\n)" --no-verify', True),
            ('git -c "core.hooksPath=/dev/null" commit -m x', True),
            ("git -c core.hooksPath=.githooks commit -m x", False),
            ('git commit -m "docs: pass -n to head"', False),
            ("git commit -m x\nhead -n 3 f", False),
            ("git commit -mn", False),
        ]
        for command, flagged in cases:
            with self.subTest(command=command):
                self.assertEqual("skipped the project's commit hooks" in hook_output(self.repo, command), flagged)

    def test_checks_text_posted_by_every_route(self):
        body = os.path.join(self.repo, "body.md")
        with open(body, "w") as f:
            f.write("Adds tax.\n\nGenerated with Claude Code\n")
        cases = [
            ("gh api repos/o/r/pulls -f title='feat: tax' -f body='I added tax.'", "first person"),
            ('gh pr review 4 --comment --body "We should round later."', "first person"),
            ('gh pr merge 4 --squash --body "Merged after I checked it."', "first person"),
            ("gh pr create --title 'feat: tax' --body-file body.md", "credits an AI tool"),
            ('gh pr create --title "feat: tax" --body-file "body.md"', "credits an AI tool"),
            ("gh pr create --title 'feat: tax' --body-file 'body.md'", "credits an AI tool"),
            ("gh api repos/o/r/pulls -f title=x -F body=@body.md", "credits an AI tool"),
            ('gh pr create --title "feat: tax" --body "Adds tax.\n\nI checked the rounding."', "first person"),
            ('gh pr create --assignee @me --title "feat: tax" --body "Adds tax."', None),
            ("gh api repos/o/r/commits/abc", None),
        ]
        for command, flag in cases:
            with self.subTest(command=command):
                out = hook_output(self.repo, command)
                if flag:
                    self.assertIn(flag, out)
                else:
                    self.assertEqual(out, "")

    def test_a_scope_is_not_first_person(self):
        git(self.repo, "commit", "-q", "--allow-empty", "-m", "fix(us): use the US date format\n\nDates read month first.")
        self.assertEqual(hook_output(self.repo, "git commit -m x"), "")

    def test_answers_in_the_shape_each_tool_reads(self):
        # Claude Code reads hookSpecificOutput; Copilot CLI reads only a top-level additionalContext.
        git(self.repo, "commit", "-q", "--allow-empty", "-m", "Add stuff")
        claude = json.loads(hook_output(self.repo, "git commit -m 'Add stuff'"))
        copilot = json.loads(hook_output(self.repo, "git commit -m 'Add stuff'", copilot=True))
        self.assertIn("isn't Conventional Commits", claude["hookSpecificOutput"]["additionalContext"])
        self.assertIn("isn't Conventional Commits", copilot["additionalContext"])


if __name__ == "__main__":
    unittest.main()
