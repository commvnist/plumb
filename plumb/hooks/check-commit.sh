#!/bin/sh
# Runs after each shell command. Skill text alone can't guarantee a commit's
# message, so this catches a commit just made whose subject isn't Conventional
# Commits, that credits an AI tool, is in the first person or has no body, and asks
# the agent to fix it while it's still unpushed and cheap.
input=$(cat)

# Only the command counts: a command's output can mention commits too.
command=$(printf '%s' "$input" | grep -Eo '"command" *: *"([^"\\]|\\.)*"' | head -n 1)
printf '%s' "$command" | grep -Eq '(^|[^[:alnum:]_-])git([[:space:]][^;&|]*)?[[:space:]]commit([[:space:]]|\\|"|$)' || exit 0

dir=$(printf '%s' "$input" | grep -o '"cwd" *: *"[^"]*"' | head -n 1 | sed 's/.*: *"//; s/"$//')
[ -n "$dir" ] || dir=.
git -C "$dir" rev-parse --git-dir >/dev/null 2>&1 || exit 0

# Only a commit this command made: the newest reflog entry is a commit, and recent.
entry=$(git -C "$dir" reflog -1 --date=unix --format='%gd %gs' 2>/dev/null) || exit 0
case $entry in
  *"} commit (merge):"*) exit 0 ;;
  *"} commit"*) ;;
  *) exit 0 ;;
esac
made=$(printf '%s' "$entry" | sed 's/^[^{]*{\([0-9]*\)}.*/\1/')
[ $(( $(date +%s) - made )) -le 120 ] || exit 0

subject=$(git -C "$dir" log -1 --format=%s)
body=$(git -C "$dir" log -1 --format=%b)
note=""
if ! printf '%s\n' "$subject" | grep -Eq '^(feat|fix|perf|refactor|test|docs|build|ci|chore|style|revert)(\([^()]+\))?!?: [^ ]'; then
  note=" Its subject isn't Conventional Commits; fix that unless the user or the project's written rules asked for another format."
fi
# Charter rule 20: a trailer or credit line naming an AI tool, or first-person wording. A credit line
# starts with the credit, so prose that only mentions a tool or AI ("generated by the database cursor") passes.
if printf '%s\n' "$body" | grep -Eiq '^(co-authored-by|generated-by|assisted-by|[a-z]+-session):.*(claude|anthropic|openai|codex|copilot|gemini|cursor|\bai\b)|^[^[:alnum:]]*(generated|written|created) (with|by) [^[:alnum:]]*(claude|codex|copilot|gemini|chatgpt|cursor|an? ai\b|ai\b)'; then
  note="$note It credits an AI tool (a co-author, generated-by or session line); remove that, as charter rule 20 says, unless the user or the project's written rules asked for it."
fi
# Whole words only, so I/O, my_var and us-east-1 pass.
if printf '%s\n%s\n' "$subject" "$body" | grep -Eq "(^|[^[:alnum:]_/'-])(I|I'm|I've|I'll|I'd|[Mm]e|[Mm]y|mine|[Ww]e|[Ww]e're|[Ww]e've|[Uu]s|[Oo]ur|ours)([^[:alnum:]_/'-]|$)"; then
  note="$note It is written in the first person; reword it in a neutral technical voice, as charter rule 20 says."
fi
if [ -z "$(printf '%s' "$body" | tr -d '[:space:]')" ]; then
  note="$note It has no body; add one saying why the change was needed, as plumb-ship says, unless the user or the project's written rules asked for another format."
fi
[ -n "$note" ] || exit 0

note="plumb: check the commit just made.$note Load plumb-ship and amend the message, keeping the rest of the body. If the commit is already pushed, don't rewrite it: tell the user and propose the corrected message."
# Copilot CLI reads context only from a top-level field; Claude Code from hookSpecificOutput.
if [ -n "$COPILOT_PLUGIN_ROOT" ]; then
  printf '{"additionalContext":"%s"}\n' "$note"
else
  printf '{"hookSpecificOutput":{"hookEventName":"PostToolUse","additionalContext":"%s"}}\n' "$note"
fi
