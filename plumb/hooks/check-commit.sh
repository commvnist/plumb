#!/bin/sh
# Runs after each shell command. Skill text alone can't guarantee a commit's
# message, so this catches a commit just made whose subject isn't Conventional
# Commits, that credits an AI tool, is in the first person, has no body or skipped
# the project's hooks, and asks the agent to fix it while it's still unpushed and
# cheap. Pull request, review and issue text posted with gh is held to the same voice.
input=$(cat)

# Only the command counts: a command's output can mention commits too.
command=$(printf '%s' "$input" | grep -Eo '"command" *: *"([^"\\]|\\.)*"' | head -n 1)

say() {
  # Copilot CLI reads context only from a top-level field; Claude Code from hookSpecificOutput.
  if [ -n "$COPILOT_PLUGIN_ROOT" ]; then
    printf '{"additionalContext":"%s"}\n' "$1"
  else
    printf '{"hookSpecificOutput":{"hookEventName":"PostToolUse","additionalContext":"%s"}}\n' "$1"
  fi
}

# Charter rule 20: a trailer or credit line naming an AI tool. A credit line starts with the credit,
# so prose that only mentions a tool or AI ("generated by the database cursor") passes.
CREDIT='(^|\\n)(co-authored-by|generated-by|assisted-by|[a-z]+-session):.*(claude|anthropic|openai|codex|copilot|gemini|cursor|\bai\b)|(^|\\n)[^[:alnum:]\\]*(generated|written|created) (with|by) [^[:alnum:]]*(claude|codex|copilot|gemini|chatgpt|cursor|an? ai\b|ai\b)'
# Whole words only, so I/O, my_var, us-east-1 and @me pass. Posted text arrives JSON-escaped, where a
# new paragraph starts after a literal \n.
FIRST="(^|\\\\n|[^[:alnum:]_/@-])(I|I'm|I've|I'll|I'd|[Mm]e|[Mm]y|mine|[Ww]e|[Ww]e're|[Ww]e've|[Uu]s|[Oo]ur|ours)([^[:alnum:]_/'-]|$)"

dir=$(printf '%s' "$input" | grep -Eo '"cwd" *: *"([^"\\]|\\.)*"' | head -n 1 | sed 's/.*: *"//; s/"$//; s/\\\\/\\/g')
[ -n "$dir" ] || dir=.

# Text posted to a pull request, review or issue is held to the same voice as a commit message,
# whether it is written inline, read from a file, or sent through the API.
if printf '%s' "$command" | grep -Eq '(^|[^[:alnum:]_-])gh[[:space:]]+((pr|issue)[[:space:]]+(create|edit|comment|review|merge)|api[[:space:]][^;&|]*(pulls|issues|comments|reviews))'; then
  posted=$(printf '%s' "$command" | sed 's/^"command" *: *"//; s/"$//')
  # A path may be quoted, and gh api -F reads a file named after =@.
  for file in $(printf '%s' "$posted" | grep -Eo -- "(--body-file|--input|-F)[[:space:]=]*(\\\\\"|')?[^[:space:]\"'\\\\;&|]+" \
    | sed -E "s/^(--body-file|--input|-F)[[:space:]=]*(\\\\\"|')?//; s/^[^=@]*=@//"); do
    case $file in /*) ;; *) file="$dir/$file" ;; esac
    [ -r "$file" ] && posted="$posted\\n$(sed 's/$/\\n/' "$file" | tr -d '\n')"
  done
  note=""
  printf '%s\n' "$posted" | grep -Eiq "$CREDIT" \
    && note=" It credits an AI tool; remove that, as charter rule 20 says, unless the operator or the project's rules asked for it."
  printf '%s\n' "$posted" | grep -Eq "$FIRST" \
    && note="$note It is written in the first person; reword it in a neutral technical voice, as charter rule 20 says."
  [ -n "$note" ] && say "plumb: check the text just posted.$note Edit it in place (gh pr edit, gh issue edit or the comment's edit) and tell the operator."
  exit 0
fi

printf '%s' "$command" | grep -Eq '(^|[^[:alnum:]_-])git([[:space:]][^;&|]*)?[[:space:]]commit([[:space:]]|\\|"|$)' || exit 0

# The commit may be in another repository than the session's folder: git -C <dir>, or a cd before it.
target=$(printf '%s' "$command" | sed -n 's/.*git[[:space:]][[:space:]]*-C[[:space:]][[:space:]]*\([^[:space:];&|]*\).*/\1/p' | head -n 1)
[ -n "$target" ] || target=$(printf '%s' "$command" | grep -Eo '(: *"|[;&|]|\\n)[[:space:]]*cd[[:space:]]+[^;&|[:space:]]+' | tail -n 1 | sed 's/.*cd[[:space:]]*//')
target=$(printf '%s' "$target" | sed 's/\\"//g; s/^"//; s/"$//')
case $target in
  '') ;;
  /*) git -C "$target" rev-parse --git-dir >/dev/null 2>&1 && dir=$target ;;
  *) git -C "$dir/$target" rev-parse --git-dir >/dev/null 2>&1 && dir="$dir/$target" ;;
esac
git -C "$dir" rev-parse --git-dir >/dev/null 2>&1 || exit 0

# Only a commit this command made: the newest reflog entry is a commit, and recent.
entry=$(git -C "$dir" reflog -1 --date=unix --format='%gd %gs' 2>/dev/null) || exit 0
case $entry in
  *"} commit (merge):"*) exit 0 ;;
  *"} commit"*) ;;
  *) exit 0 ;;
esac
made=$(printf '%s' "$entry" | sed 's/^[^{]*{\([0-9]*\)}.*/\1/')
[ $(( $(date +%s) - made )) -le 120 ] || exit 0
# commit's own arguments: quoted text (a message, a heredoc) is dropped, so a message saying "commit",
# "-n" or "-q" doesn't count, and the command is cut at the next separator.
Q=$(printf '\001')
commit_args=$(printf '%s' "$command" | sed 's/^"command" *: *"//; s/"$//' \
  | sed "s/\\\\\"/$Q/g; s/$Q[^$Q]*$Q//g; s/'[^']*'//g; s/\\\\n/;/g" | tr ';&|' '\n\n\n' \
  | grep -E -m 1 '(^|[^[:alnum:]_-])git([[:space:]].*)?[[:space:]]commit([[:space:]]|$)' \
  | sed -E 's/.*[[:space:]]commit([[:space:]]|$)/ /')
# A recent commit may be the operator's, made just before this command failed or made none. Where the tool
# reports the command's output (Copilot CLI doesn't), git's success line ("[main 1a2b3c4] subject") must name
# HEAD; a quiet commit prints none, so there only a failure message rules it out.
if printf '%s' "$input" | grep -Eq '"tool_response" *:'; then
  response=$(printf '%s' "$input" | sed -n 's/.*"tool_response" *: *//p')
  head_sha=$(git -C "$dir" rev-parse HEAD)
  mine=""
  for sha in $(printf '%s' "$response" | grep -Eo '\[[^]"]* [0-9a-f]{7,40}\]' | sed 's/.* \([0-9a-f]*\)\]$/\1/'); do
    case $head_sha in "$sha"*) mine=1 ;; esac
  done
  if [ -z "$mine" ]; then
    printf '%s' "$commit_args" | grep -Eq '[[:space:]](--quiet|-[a-zA-Z]*q[a-zA-Z]*)([[:space:]]|$)' || exit 0
    printf '%s' "$response" | grep -Eiq 'nothing to commit|nothing added to commit|no changes added|failed|(^|[^[:alnum:]])(error|fatal):' && exit 0
  fi
fi

subject=$(git -C "$dir" log -1 --format=%s)
body=$(git -C "$dir" log -1 --format=%b)
note=""
if ! printf '%s\n' "$subject" | grep -Eq '^(feat|fix|perf|refactor|test|docs|build|ci|chore|style|revert)(\([^()]+\))?!?: [^ ]'; then
  note=" Its subject isn't Conventional Commits; fix that unless the operator or the project's rules asked for another format."
fi
if printf '%s\n' "$body" | grep -Eiq "$CREDIT"; then
  note="$note It credits an AI tool (a co-author, generated-by or session line); remove that, as charter rule 20 says, unless the operator or the project's rules asked for it."
fi
# A Conventional Commits scope such as (us) names an area, not the writer.
if printf '%s\n%s\n' "$(printf '%s' "$subject" | sed 's/^[a-z]*([^)]*)//')" "$body" | grep -Eq "$FIRST"; then
  note="$note It is written in the first person; reword it in a neutral technical voice, as charter rule 20 says."
fi
if [ -z "$(printf '%s' "$body" | tr -d '[:space:]')" ]; then
  note="$note It has no body; add one saying why the change was needed, as plumb-ship says, unless the operator or the project's rules asked for another format."
fi
# --no-verify, -n alone or among commit's argument-free short flags, or hooks pointed at nothing.
if printf '%s' "$commit_args" | grep -Eq '[[:space:]](--no-verify|-[aqsve]*n[aqsve]*m?)([[:space:]]|$)' \
  || printf '%s' "$command" | grep -Eq -- "-c[[:space:]]*(\\\\\"|')?core\.hooks[Pp]ath=(/dev/null|\\\\\"|'|[[:space:]]|$)"; then
  note="$note It skipped the project's commit hooks (--no-verify, -n or core.hooksPath set to nothing); run them, unless the operator asked to skip them."
fi
[ -n "$note" ] || exit 0

say "plumb: check the commit just made.$note Load plumb-ship and amend the message, keeping the rest of the body. If the commit is already pushed, don't rewrite it: tell the operator and propose the corrected message."
