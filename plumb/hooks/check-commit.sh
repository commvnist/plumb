#!/bin/sh
# Runs after each shell command. Skill text alone can't guarantee a commit's
# message, so this catches a commit just made whose subject isn't Conventional
# Commits, that credits an AI tool, is in the first person, has no body or skipped
# the project's hooks, and asks the agent to fix it while it's still unpushed and
# cheap. Pull request, review and issue text posted with gh is held to the same voice.
input=$(cat)

# Only the command counts: a command's output can mention commits too.
command=$(printf '%s' "$input" | grep -Eo '"command" *: *"([^"\\]|\\.)*"' | head -n 1)

say() {
  # Copilot CLI reads context only from a top-level field; Claude Code from hookSpecificOutput.
  if [ -n "$COPILOT_PLUGIN_ROOT" ]; then
    printf '{"additionalContext":"%s"}\n' "$1"
  else
    printf '{"hookSpecificOutput":{"hookEventName":"PostToolUse","additionalContext":"%s"}}\n' "$1"
  fi
}

# Charter rule 19: a trailer or credit line naming an AI tool. A credit line starts with the credit,
# so prose that only mentions a tool or AI ("generated by the database cursor") passes.
CREDIT='(^|\\n)(co-authored-by|generated-by|assisted-by|[a-z]+-session):.*(claude|anthropic|openai|codex|copilot|gemini|cursor|\bai\b)|(^|\\n)[^[:alnum:]\\]*(generated|written|created) (with|by) [^[:alnum:]]*(claude|codex|copilot|gemini|chatgpt|cursor|an? ai\b|ai\b)'
# Whole words only, so I/O, my_var, us-east-1 and @me pass. Posted text arrives JSON-escaped, where a
# new paragraph starts after a literal \n.
FIRST="(^|\\\\n|[^[:alnum:]_/@-])(I|I'm|I've|I'll|I'd|[Mm]e|[Mm]y|mine|[Ww]e|[Ww]e're|[Ww]e've|[Uu]s|[Oo]ur|ours)([^[:alnum:]_/'-]|$)"

dir=$(printf '%s' "$input" | grep -Eo '"cwd" *: *"([^"\\]|\\.)*"' | head -n 1 | sed 's/.*: *"//; s/"$//; s/\\\\/\\/g')
[ -n "$dir" ] || dir=.

# The command without its heredoc bodies, then also without quoted text (a message), so a message naming
# "git commit", "gh pr create", "-n" or "-q" doesn't count; each separator starts a new line.
Q=$(printf '\001')
unheredoc=$(printf '%s' "$command" | sed 's/^"command" *: *"//; s/"$//' \
  | awk '{ gsub(/\\n/, "\n"); print }' \
  | awk -v q="'" 'BEGIN { op = "(^|[^<])<<-?[ \t]*[\\\\\"" q "]*[A-Za-z_][A-Za-z0-9_]*" }
      skip { line = $0; sub(/^([ \t]|\\t)*/, "", line); if (line == end) skip = 0; next }
      { print; if (match($0, op)) { end = substr($0, RSTART, RLENGTH); sub(/^.*<<-?[ \t]*/, "", end)
          gsub(/[^A-Za-z0-9_]/, "", end); skip = 1 } }' \
  | awk 'BEGIN { ORS = "\\n" } { print }')
skeleton=$(printf '%s' "$unheredoc" \
  | sed "s/\\\\\"/$Q/g" \
  | awk -v q="'" -v d="$Q" '{ out = ""; s = 0
      # Left to right, so a double quote inside single quotes (or the reverse) opens nothing.
      for (i = 1; i <= length($0); i++) { c = substr($0, i, 1)
        if (s == 0) { if (c == q) s = 1; else if (c == d) s = 2; else out = out c }
        else if ((s == 1 && c == q) || (s == 2 && c == d)) s = 0 }
      print out }' \
  | sed 's/\\n/;/g' | tr ';&|' '\n\n\n')

# Text posted to a pull request, review or issue is held to the same voice as a commit message,
# whether it is written inline, read from a file, or sent through the API.
# A quoted gh (bash -c '...') still posts, so only heredoc bodies are left out here.
if printf '%s' "$unheredoc" | grep -Eq '(^|[^[:alnum:]_-]|\\n)gh[[:space:]]+((pr|issue)[[:space:]]+(create|edit|comment|review|merge)|api[[:space:]][^;&|]*(pulls|issues|comments|reviews))'; then
  posted=$(printf '%s' "$command" | sed 's/^"command" *: *"//; s/"$//')
  # A path may be quoted, and gh api -F reads a file named after =@.
  note=""
  for file in $(printf '%s' "$posted" | grep -Eo -- "(--body-file|--input|-F)[[:space:]=]*(\\\\\"|')?[^[:space:]\"'\\\\;&|]+" \
    | sed -E "s/^(--body-file|--input|-F)[[:space:]=]*(\\\\\"|')?//; s/^[^=@]*=@//"); do
    # A body read from standard input is in the command itself, already checked; an -F field without
    # =@ is a value, not a file.
    case $file in -|*=*) continue ;; /*) path=$file ;; *) path="$dir/$file" ;; esac
    if [ -r "$path" ]; then
      posted="$posted\\n$(sed 's/$/\\n/' "$path" | tr -d '\n')"
      [ -n "$(tr -d '[:space:]' < "$path")" ] || note="$note The file $file is empty, so the post is blank; if it replaced text, restore that from the live version's history."
    else
      note="$note plumb couldn't read $file here (it may be on another machine), so its text went unchecked: check it against charter rule 19."
    fi
  done
  printf '%s' "$posted" | grep -Eq -- "(--body|-b)([[:space:]]+|=)(\\\\\"\\\\\"|'')([[:space:]]|$)" \
    && note="$note The body is empty, so the post is blank; if it replaced text, restore that from the live version's history."
  printf '%s\n' "$posted" | grep -Eiq "$CREDIT" \
    && note="$note It credits an AI tool; remove that, as charter rule 19 says, unless the operator or the project's rules asked for it."
  printf '%s\n' "$posted" | grep -Eq "$FIRST" \
    && note="$note It is written in the first person; reword it in a neutral technical voice, as charter rule 19 says."
  [ -n "$note" ] && say "plumb: check the text just posted.$note Edit it in place (gh pr edit, gh issue edit or the comment's edit) and tell the operator."
  exit 0
fi

# A newline inside the JSON command is the two characters \n, so it counts as a boundary too.
printf '%s' "$command" | grep -Eq '(^|[^[:alnum:]_-]|\\n)git([[:space:]][^;&|]*)?[[:space:]]commit([[:space:]]|\\|"|$)' || exit 0

# commit's own arguments, cut at the next separator.
commit_args=$(printf '%s\n' "$skeleton" \
  | grep -E -m 1 '(^|[^[:alnum:]_-])git([[:space:]].*)?[[:space:]]commit([[:space:]]|$)' \
  | sed -E 's/.*[[:space:]]commit([[:space:]]|$)/ /')

# The message a commit is given in the command itself: each -m or --message string (quoted once, or again
# inside a quoted remote command), and a heredoc that
# feeds -F - or --file=-. Shell words around them (a host, a script's comments) aren't the message.
messages=$( { printf '%s' "$command" | grep -Eo '(-m|--message)[[:space:]=]+('"'"'[^'"'"']*'"'"'|\\\\\\"[^"]*\\\\\\"|\\"([^\\]|\\[^"])*\\")' \
    | sed -E "s/^(-m|--message)[[:space:]=]+('|(\\\\\\\\)?\\\\\")//; s/('|(\\\\\\\\)?\\\\\")\$//; s/\$/\\\\n/" ;
  printf '%s' "$command" | sed 's/^"command" *: *"//; s/"$//' | awk '{ gsub(/\\n/, "\n"); print }' \
    | awk -v q="'" 'BEGIN { op = "(^|[^<])<<-?[ \t]*[\\\\\"" q "]*[A-Za-z_][A-Za-z0-9_]*" }
        take { line = $0; sub(/^([ \t]|\\t)*/, "", line); if (line == end) take = 0; else printf "%s\\n", $0; next }
        $0 ~ /commit/ && $0 ~ /(-F|--file)[ =]*-([ \t]|$|<)/ && match($0, op) {
          end = substr($0, RSTART, RLENGTH); sub(/^.*<<-?[ \t]*/, "", end); gsub(/[^A-Za-z0-9_]/, "", end); take = 1 }' ; } | tr -d '\n')

# A commit only inside text handed to another program (a remote shell, a container, a job runner's
# heredoc) may run where no repository here holds it. A local repository is still checked first.
handed=""
if [ -z "$commit_args" ]; then
  [ -n "$messages" ] || exit 0
  handed=1
fi
not_here() {
  # No commit this command made is in a repository here: for a handed-off commit, its text is all there is.
  [ -n "$handed" ] || exit 0
  printf '%s' "$response" | grep -Eiq 'nothing to commit|nothing added to commit|no changes added|(^|[^[:alnum:]])(error|fatal):' && exit 0
  note=""
  printf '%s\n' "$messages" | grep -Eiq "$CREDIT" \
    && note=" Its message credits an AI tool; remove that, as charter rule 19 says, unless the operator or the project's rules asked for it."
  printf '%s\n' "$messages" | grep -Eq "$FIRST" \
    && note="$note Its message is in the first person; reword it in a neutral technical voice, as charter rule 19 says."
  unseen="plumb: this command hands a commit to another program, where the commit check can't read it."
  if [ -n "$note" ]; then
    say "$unseen$note Amend it where it ran while it's unpushed; if it's pushed, tell the operator and propose the corrected message."
    exit 0
  fi
  # A clean message is pointed out once a session (or subagent), where its transcript shows it was said.
  transcript=$(printf '%s' "$input" | grep -Eo '"transcript_path" *: *"([^"\\]|\\.)*"' | head -n 1 \
    | sed 's/.*: *"//; s/"$//; s/\\\\/\\/g')
  agent=$(printf '%s' "$input" | grep -Eo '"agent_id" *: *"[A-Za-z0-9_-]+"' | head -n 1 | sed 's/.*: *"//; s/"$//')
  [ -n "$agent" ] && transcript="${transcript%.jsonl}/subagents/agent-$agent.jsonl"
  [ -r "$transcript" ] && grep -qF "$unseen" "$transcript" && exit 0
  say "$unseen Check the commit it made against plumb-ship and charter rule 19 where it ran, and amend it there while it's unpushed."
  exit 0
}
response=$(printf '%s' "$input" | sed -n 's/.*"tool_response" *: *//p')

# The commit may be in another repository than the session's folder: git -C <dir>, or a cd before it.
target=$(printf '%s' "$command" | sed -n 's/.*git[[:space:]][[:space:]]*-C[[:space:]][[:space:]]*\([^[:space:];&|]*\).*/\1/p' | head -n 1)
[ -n "$target" ] || target=$(printf '%s' "$command" | grep -Eo '(: *"|[;&|]|\\n)[[:space:]]*cd[[:space:]]+[^;&|[:space:]]+' | tail -n 1 | sed 's/.*cd[[:space:]]*//; s/\\n.*//')
target=$(printf '%s' "$target" | sed 's/\\"//g; s/^"//; s/"$//')
case $target in
  '') ;;
  /*) git -C "$target" rev-parse --git-dir >/dev/null 2>&1 && dir=$target ;;
  *) git -C "$dir/$target" rev-parse --git-dir >/dev/null 2>&1 && dir="$dir/$target" ;;
esac
git -C "$dir" rev-parse --git-dir >/dev/null 2>&1 || not_here

# Only a commit this command made: the newest reflog entry is a commit, and recent.
entry=$(git -C "$dir" reflog -1 --date=unix --format='%gd %gs' 2>/dev/null) || not_here
case $entry in
  *"} commit (merge):"*) exit 0 ;;
  *"} commit"*) ;;
  *) not_here ;;
esac
made=$(printf '%s' "$entry" | sed 's/^[^{]*{\([0-9]*\)}.*/\1/')
[ $(( $(date +%s) - made )) -le 120 ] || not_here
# A recent commit may be the operator's, made just before this command failed or made none. Where the tool
# reports the command's output (Copilot CLI doesn't), git's success line ("[main 1a2b3c4] subject") must name
# HEAD; a quiet commit prints none, so there only a failure message rules it out.
if printf '%s' "$input" | grep -Eq '"tool_response" *:'; then
  head_sha=$(git -C "$dir" rev-parse HEAD)
  mine=""
  for sha in $(printf '%s' "$response" | grep -Eo '\[[^]"]* [0-9a-f]{7,40}\]' | sed 's/.* \([0-9a-f]*\)\]$/\1/'); do
    case $head_sha in "$sha"*) mine=1 ;; esac
  done
  if [ -z "$mine" ]; then
    [ -n "$handed" ] && not_here
    printf '%s' "$commit_args" | grep -Eq '[[:space:]](--quiet|-[a-zA-Z]*q[a-zA-Z]*)([[:space:]]|$)' || exit 0
    printf '%s' "$response" | grep -Eiq 'nothing to commit|nothing added to commit|no changes added|failed|(^|[^[:alnum:]])(error|fatal):' && exit 0
  fi
fi

subject=$(git -C "$dir" log -1 --format=%s)
body=$(git -C "$dir" log -1 --format=%b)
note=""
if ! printf '%s\n' "$subject" | grep -Eq '^(feat|fix|perf|refactor|test|docs|build|ci|chore|style|revert)(\([^()]+\))?!?: [^ ]'; then
  note=" Its subject isn't Conventional Commits; fix that unless the operator or the project's rules asked for another format."
fi
if printf '%s\n' "$body" | grep -Eiq "$CREDIT"; then
  note="$note It credits an AI tool (a co-author, generated-by or session line); remove that, as charter rule 19 says, unless the operator or the project's rules asked for it."
fi
# A Conventional Commits scope such as (us) names an area, not the writer.
if printf '%s\n%s\n' "$(printf '%s' "$subject" | sed 's/^[a-z]*([^)]*)//')" "$body" | grep -Eq "$FIRST"; then
  note="$note It is written in the first person; reword it in a neutral technical voice, as charter rule 19 says."
fi
if [ -z "$(printf '%s' "$body" | tr -d '[:space:]')" ]; then
  note="$note It has no body; add one saying why the change was needed, as plumb-ship says, unless the operator or the project's rules asked for another format."
fi
# --no-verify, -n alone or among commit's argument-free short flags, or hooks pointed at nothing.
if printf '%s' "$commit_args" | grep -Eq '[[:space:]](--no-verify|-[aqsve]*n[aqsve]*m?)([[:space:]]|$)' \
  || printf '%s' "$command" | grep -Eq -- "-c[[:space:]]*(\\\\\"|')?core\.hooks[Pp]ath=(/dev/null|\\\\\"|'|[[:space:]]|$)"; then
  note="$note It skipped the project's commit hooks (--no-verify, -n or core.hooksPath set to nothing); run them, unless the operator asked to skip them."
fi
[ -n "$note" ] || exit 0

say "plumb: check the commit just made.$note Load plumb-ship and amend the message, keeping the rest of the body. If the commit is already pushed, don't rewrite it: tell the operator and propose the corrected message."
